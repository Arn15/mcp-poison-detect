"""Write docs/CODE_REFERENCE.md: every module and script with its classes and functions, from their docstrings.

    python scripts/gen_code_reference.py      # re-run after changing code; CPU, < 1 s
"""
from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def first(doc: str | None) -> str:
    """First paragraph of a docstring on one line (empty if none)."""
    return " ".join((doc or "").strip().split("\n\n")[0].split()).replace("|", "\\|")


def sig(n: ast.FunctionDef) -> str:
    """Argument names of a function, without self / annotations / defaults."""
    a = [x.arg for x in n.args.posonlyargs + n.args.args if x.arg not in ("self", "cls")]
    if n.args.vararg:
        a.append("*" + n.args.vararg.arg)
    a += [x.arg for x in n.args.kwonlyargs]
    if n.args.kwarg:
        a.append("**" + n.args.kwarg.arg)
    return f"{n.name}({', '.join(a)})"


def section(path: Path) -> list[str]:
    """Markdown for one file: module summary + table of public classes / functions (and class methods)."""
    t = ast.parse(path.read_text())
    rel = path.relative_to(ROOT).as_posix()
    out = [f"### `{rel}`", "", first(ast.get_docstring(t)) or "—", ""]
    rows = []
    for n in t.body:
        if isinstance(n, ast.FunctionDef) and not n.name.startswith("_"):
            d = first(ast.get_docstring(n)) or (n.name[5:].replace("_", " ").capitalize() + " (test)"
                                                if n.name.startswith("test_") else "")
            rows.append(f"| `{sig(n)}` | function | {d} |")
        elif isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
            rows.append(f"| `{n.name}` | class | {first(ast.get_docstring(n))} |")
            for m in n.body:
                if isinstance(m, ast.FunctionDef) and (not m.name.startswith("_")) and ast.get_docstring(m):
                    rows.append(f"| `{n.name}.{sig(m)}` | method | {first(ast.get_docstring(m))} |")
    if rows:
        out += ["| Name | Kind | Description |", "|---|---|---|", *rows, ""]
    return out


def main():
    """Build docs/CODE_REFERENCE.md."""
    L = ["# Code reference", "",
         "Generated by `scripts/gen_code_reference.py` from the docstrings. All files were written for this project "
         "(with Claude as an AI coding assistant; see `CONTRIBUTIONS.md`, which also lists the ones that adapt a "
         "published method).", ""]
    for title, files in (("Package `mcptp/`", sorted(p for p in (ROOT / "mcptp").rglob("*.py")
                                                         if p.name != "__init__.py")),
                         ("Scripts `scripts/`", sorted((ROOT / "scripts").glob("*.py"))),
                         ("Tests `tests/`", sorted((ROOT / "tests").glob("test_*.py")))):
        L += [f"## {title}", ""]
        for f in files:
            L += section(f)
    (ROOT / "docs" / "CODE_REFERENCE.md").write_text("\n".join(L))
    print("wrote docs/CODE_REFERENCE.md")


if __name__ == "__main__":
    main()
